// Generates the winmm.dll proxy's export stubs from the system DLL's export table.
// Usage: node gen-proxy.js <dumpbin /exports output> <outDir>
// Writes exports.asm (one stub per export), winmm.def and exports.h (names/ordinals table).
const fs = require("fs");
const [dump, outDir] = process.argv.slice(2);

const exportsList = [];
let inTable = false;
for (const line of fs.readFileSync(dump, "utf8").split(/\r?\n/)) {
  if (/ordinal\s+hint\s+RVA\s+name/.test(line)) { inTable = true; continue; }
  if (!inTable) continue;
  if (/^\s*Summary/.test(line)) break;
  let m = line.match(/^\s+(\d+)\s+[0-9A-F]+\s+[0-9A-F]{8}\s+(\S+)/); // ordinal hint rva name
  if (m) { exportsList.push({ ordinal: +m[1], name: m[2] }); continue; }
  m = line.match(/^\s+(\d+)\s+[0-9A-F]{8}\s+\[NONAME\]/);            // ordinal rva [NONAME]
  if (m) exportsList.push({ ordinal: +m[1], name: null });
}
if (!exportsList.length) throw new Error("no exports parsed");

const stub = e => e.name ? `Proxy_${e.name}` : `Proxy_Ordinal${e.ordinal}`;
const n = exportsList.length;

let asm = `; Generated by gen-proxy.js: every export jumps to the same export of the system DLL.
; System DLLs that import the proxied DLL may call it before its DllMain has run, so an empty
; slot first resolves the table (EnsureSystemDll).

EXTERN EnsureSystemDll:PROC

.data
PUBLIC ProxyProcs
ProxyProcs QWORD ${n} DUP(0)

.code
; r11 = export index. Keeps the argument registers, fills the table, then jumps.
ResolveAndJump PROC
    push rcx
    push rdx
    push r8
    push r9
    sub rsp, 68h
    mov [rsp + 60h], r11
    movdqu [rsp + 20h], xmm0
    movdqu [rsp + 30h], xmm1
    movdqu [rsp + 40h], xmm2
    movdqu [rsp + 50h], xmm3
    call EnsureSystemDll
    movdqu xmm0, [rsp + 20h]
    movdqu xmm1, [rsp + 30h]
    movdqu xmm2, [rsp + 40h]
    movdqu xmm3, [rsp + 50h]
    mov r11, [rsp + 60h]
    add rsp, 68h
    pop r9
    pop r8
    pop rdx
    pop rcx
    lea rax, ProxyProcs
    jmp qword ptr [rax + r11 * 8]
ResolveAndJump ENDP

`;
exportsList.forEach((e, i) => {
  asm += `${stub(e)} PROC
    mov rax, qword ptr [ProxyProcs + ${i} * 8]
    test rax, rax
    jz @F
    jmp rax
@@:
    mov r11, ${i}
    jmp ResolveAndJump
${stub(e)} ENDP

`;
});
asm += "END\n";

let def = "LIBRARY winmm\nEXPORTS\n";
for (const e of exportsList)
  def += e.name ? `    ${e.name}=${stub(e)} @${e.ordinal}\n` : `    ${stub(e)} @${e.ordinal} NONAME\n`;

let header = `#pragma once\n// Generated by gen-proxy.js: same order as ProxyProcs in exports.asm.\n#include <cstdint>\n\n` +
  `struct ProxyExport { const char* Name; uint16_t Ordinal; };\n` +
  `inline constexpr int ProxyExportCount = ${n};\n` +
  `inline const ProxyExport ProxyExports[ProxyExportCount] = {\n` +
  exportsList.map(e => `    {${e.name ? `"${e.name}"` : "nullptr"}, ${e.ordinal}},`).join("\n") + "\n};\n";

fs.writeFileSync(`${outDir}/exports.asm`, asm);
fs.writeFileSync(`${outDir}/winmm.def`, def);
fs.writeFileSync(`${outDir}/exports.h`, header);
console.log(`${n} exports (${exportsList.filter(e => !e.name).length} by ordinal only)`);
