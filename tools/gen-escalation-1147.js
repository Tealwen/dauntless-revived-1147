// gen-escalation-1147.js - the 1.14.7 Escalation season registry for the metagame's ESCALATION_MODE=real
// (UndauntedMetagame/src/vendor/escalation/seasons_1147.json, same shape as the 1.4.4 seasons.json).
// Input: the decoded (uasset.js json) 1.14.7 tables
//   prog.json        /Game/gamemodes/escalation/base_blueprints/escalation_progression (FEscalationProgressionTuning)
//   tal.json, tal_S2.json .. tal_S6.json   the talent table each row names (escalation_talents[_S<n>])
// Usage: node gen-escalation-1147.js <dir with those files> <out json>
// 1.14.7 has six seasons (Frost and Radiant are new); seasons 1-4 match the 1.4.4 registry id for id.
'use strict';
const fs = require('fs'), path = require('path');
const [, , dir, out] = process.argv;
const read = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
const enumValue = (v) => String(v ?? '').replace(/^.*::/, '');
const text = (t) => (t && typeof t.text === 'string' && t.text.length ? t.text : null);

const seasons = read('prog.json').rows.map(([id, row]) => {
  const table = row.EscalationTalentsTable.obj.split('.').pop();
  const file = 'tal' + (table.match(/_S\d+$/)?.[0] ?? '') + '.json';
  const talents = read(file).rows.map(([talentId, t]) => ({
    id: talentId,
    name: text(t.Name),
    type: enumValue(t.TalentType),
    pointsToUnlock: t.PointsToUnlock ?? 0,
    rankCosts: (t.Ranks ?? []).map((r) => r.PointCost),
  }));
  return {
    id,
    context: enumValue(row.SeasonContext),
    displayName: text(row.SeasonDisplayName) ?? id,
    enabled: row.bEnable === true,
    persistentPowerPerLevel: row.PersistentPowerPerEscalationLevel,
    levels: row.EscalationLevels.map((l) => ({ level: l.Level, requiredExperience: l.RequiredExperience })),
    talentsTable: table,
    talents,
    unlocks: row.EscalationSeasonalRewards.map((u) => ({
      id: u.UnlockId,
      unlockLevel: u.UnlockLevel,
      rewardType: enumValue(u.RewardType),
      title: text(u.UnlockTitle),
      items: (u.ItemRewards ?? []).map((i) => ({ catalogId: i.RewardItem.Item, quantity: i.RewardItem.Amount })),
    })),
  };
});

fs.writeFileSync(out, JSON.stringify({
  _comment: [
    'Escalation season registry of the 1.14.7 client (CL 647472), generated by PORT-1.14.7/tools/gen-escalation-1147.js.',
    'Source: Archon_24-WindowsClient.pak /Game/gamemodes/escalation/base_blueprints/escalation_progression (FEscalationProgressionTuning rows) and the talent tables each row names.',
    'Same shape and meaning as seasons.json (1.4.4); controllers/escalationConfig.ts loads this file when TARGET_GAME_VERSION=1.14.7.',
  ],
  revision: 'cl647472',
  source: 'Dauntless 1.14.7 paks',
  seasons,
}, null, 2) + '\n');
console.log(seasons.map((s) => `${s.id} ${s.context}: ${s.levels.length} levels, ${s.talents.length} talents, ${s.unlocks.length} unlocks`).join('\n'));
